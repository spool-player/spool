#ifdef SPOOL_ZSTD_ALLOCATOR_PROBE
extern "C" void *__real_malloc(size_t bytes);
extern "C" void __real_free(void *pointer);

extern "C" void *__wrap_malloc(size_t bytes)
{
    if (!probe.armed)
        return __real_malloc(bytes);
    ++probe.attempts;
    if (probe.failAt != 0 && probe.attempts == probe.failAt) {
        ++probe.denied;
        return nullptr;
    }
    void *pointer = __real_malloc(bytes);
    if (!pointer)
        return nullptr;
    for (auto& block : probe.blocks) {
        if (!block.pointer) {
            block = { pointer, bytes };
            probe.liveBytes += bytes;
            ++probe.liveBlocks;
            probe.peakBytes = std::max(probe.peakBytes, probe.liveBytes);
            return pointer;
        }
    }
    probe.invalid = true;
    __real_free(pointer);
    return nullptr;
}

extern "C" void __wrap_free(void *pointer)
{
    if (probe.armed && pointer) {
        bool found = false;
        for (auto& block : probe.blocks) {
            if (block.pointer == pointer) {
                probe.liveBytes -= block.bytes;
                --probe.liveBlocks;
                block = {};
                found = true;
                break;
            }
        }
        if (!found)
            probe.invalid = true;
    }
    __real_free(pointer);
}
#endif


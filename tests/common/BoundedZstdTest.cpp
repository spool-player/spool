class GuardedOutput {
public:
    explicit GuardedOutput(size_t maximum)
        : bytes(maximum + 2 * guardSize, guardByte)
    {
    }

    DecodeObservation decode(const void *source, size_t length, size_t capacity, size_t failAt = 0)
    {
        require(capacity <= bytes.size() - 2 * guardSize, "test output capacity fits its backing allocation");
        std::fill(bytes.begin(), bytes.begin() + guardSize, guardByte);
        std::fill(bytes.begin() + guardSize + capacity, bytes.end(), guardByte);
        DecodeObservation observation;
#ifdef SPOOL_ZSTD_ALLOCATOR_PROBE
        probe = {};
        probe.failAt = failAt;
        probe.armed = true;
#else
        require(failAt == 0, "allocation cuts require the production allocator probe");
#endif
        observation.result = spool_zstd_decompress(source, length, data(), capacity, &observation.written);
#ifdef SPOOL_ZSTD_ALLOCATOR_PROBE
        probe.armed = false;
        observation.attempts = probe.attempts;
        observation.peakBytes = probe.peakBytes;
        observation.denied = probe.denied;
        require(!probe.invalid, "decoder allocations obey unique ownership and bounded probe storage");
        require(probe.liveBytes == 0 && probe.liveBlocks == 0,
            "every successful or failed decode releases all live allocation bytes and blocks");
#endif
        require(std::all_of(bytes.begin(), bytes.begin() + guardSize, isGuard),
            "decoder never writes before the destination");
        require(std::all_of(bytes.begin() + guardSize + capacity, bytes.end(), isGuard),
            "decoder never writes beyond the supplied output capacity");
        return observation;
    }

    void expect(const void *source, size_t length, const std::string& expected)
    {
        const auto observation = decode(source, length, expected.size());
        require(observation.result == 0 && observation.written == expected.size(),
            "compressed frame decodes to exactly the expected byte count");
        require(std::memcmp(data(), expected.data(), expected.size()) == 0,
            "compressed literals, matches and repeated block tables reconstruct the independent expected bytes");
    }

private:
    unsigned char *data() { return bytes.data() + guardSize; }
    static bool isGuard(unsigned char byte) { return byte == guardByte; }
    static constexpr size_t guardSize = 32;
    static constexpr unsigned char guardByte = 0xa7;
    std::vector<unsigned char> bytes;
};

void compressedFramesAndCapacity()
{
    const auto large = paragraphs(640);
    const auto small = paragraphs(8);
    GuardedOutput output(large.size() + 17);
    require(spool_zstd_content_size(kMultiBlock, sizeof(kMultiBlock)) == large.size(),
        "a real compressed frame exposes its declared size before allocation");
    require(spool_zstd_content_size(kUnknownSize, sizeof(kUnknownSize)) == size_t(-1),
        "a streaming compressed frame reports its size as unknown rather than zero");
    require(spool_zstd_content_size(kEmpty, sizeof(kEmpty)) == 0, "an empty frame has a declared zero size");
    output.expect(kMultiBlock, sizeof(kMultiBlock), large);
    output.expect(kUnknownSize, sizeof(kUnknownSize), small);
    output.expect(kEmpty, sizeof(kEmpty), {});

    for (const size_t capacity : { size_t(0), size_t(1), large.size() - 1 }) {
        require(output.decode(kMultiBlock, sizeof(kMultiBlock), capacity).result == -1,
            "declared-size compressed input rejects insufficient output space");
    }
    for (const size_t capacity : { size_t(0), size_t(1), small.size() - 1 }) {
        require(output.decode(kUnknownSize, sizeof(kUnknownSize), capacity).result == -1,
            "unknown-size compressed input enforces actual output space while decoding");
    }
    const auto roomy = output.decode(kMultiBlock, sizeof(kMultiBlock), large.size() + 17);
    require(roomy.result == 0 && roomy.written == large.size(), "larger capacity does not inflate written size");
    output.expect(kMultiBlock, sizeof(kMultiBlock), large);
}

void truncationCorruptionAndRecovery()
{
    const auto large = paragraphs(640);
    const auto small = paragraphs(8);
    GuardedOutput output(large.size());
    // Every byte boundary includes header, entropy tables, literal streams,
    // sequence streams and later blocks. Errors must return, not exit or crash.
    for (size_t length = 0; length < sizeof(kMultiBlock); ++length) {
        require(output.decode(kMultiBlock, length, large.size()).result == -1,
            "every strict prefix of the multiblock compressed frame rejects as truncated");
        output.expect(kMultiBlock, sizeof(kMultiBlock), large);
    }
    for (size_t length = 0; length < sizeof(kUnknownSize); ++length) {
        require(output.decode(kUnknownSize, length, small.size()).result == -1,
            "every strict prefix of the streaming compressed frame rejects as truncated");
        output.expect(kUnknownSize, sizeof(kUnknownSize), small);
    }
    for (size_t length = 0; length < 9; ++length) {
        require(spool_zstd_content_size(kMultiBlock, length) == size_t(-1),
            "truncated declared-size headers fail without terminating the caller");
    }

    struct Damage { size_t offset; unsigned char bits; };
    // Offsets are fixture wire boundaries, not decoder internals: bad magic,
    // reserved frame bit, reserved first block, and reserved second block.
    for (const auto damage : { Damage { 0, 1 }, Damage { 4, 8 }, Damage { 9, 2 }, Damage { 364, 2 } }) {
        std::array<unsigned char, sizeof(kMultiBlock)> corrupt;
        std::copy(std::begin(kMultiBlock), std::end(kMultiBlock), corrupt.begin());
        corrupt[damage.offset] |= damage.bits;
        require(output.decode(corrupt.data(), corrupt.size(), large.size()).result == -1,
            "structurally corrupt compressed frames return a failure");
        if (damage.offset <= 4) {
            require(spool_zstd_content_size(corrupt.data(), corrupt.size()) == size_t(-1),
                "corrupt frame headers do not advertise a usable content size");
        }
        output.expect(kMultiBlock, sizeof(kMultiBlock), large);
    }
}


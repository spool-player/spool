template<size_t N>
QByteArray archiveBytes(const unsigned char (&encoded)[N])
{
    return QByteArray(reinterpret_cast<const char *>(encoded), N);
}

void expectPackage(const QByteArray& archive, const QByteArray& notes)
{
    const auto package = Spool::ProviderPackage::read(archive);
    require(package.has_value(), "the real package consumer accepts independently compressed valid USTAR input");
    require(package->manifest.id == QStringLiteral("spool.compressed-test")
            && package->manifest.entry == QStringLiteral("logic/provider.mjs"),
        "compressed manifest identity and entry reach the package consumer");
    require(package->files.size() == 3
            && package->files.value(QStringLiteral("manifest.json")) == QByteArray(kManifest)
            && package->files.value(QStringLiteral("logic/provider.mjs")) == QByteArray(kScript)
            && package->files.value(QStringLiteral("notes.txt")) == notes,
        "Huffman literals, FSE matches and later blocks deliver every independently expected member byte");
}

void rejectAndRecover(const QByteArray& damaged, const char *message,
    const QByteArray& valid, const QByteArray& notes)
{
    require(!Spool::ProviderPackage::read(damaged).has_value(), message);
    expectPackage(valid, notes);
}

void truncatedCompressedPackages(const QByteArray& valid, const QByteArray& notes)
{
    // This accepted, checksummed, multiblock package is the positive control
    // for every prefix. Even prefixes ending after an earlier compressed block
    // must not expose a partial package; the next complete read must succeed.
    for (qsizetype length = 0; length < valid.size(); ++length) {
        rejectAndRecover(valid.first(length),
            "every strict compressed-package prefix rejects without exposing a partial package", valid, notes);
    }
}

void entropyAndChecksumDamage(const QByteArray& plain, const QByteArray& checked, const QByteArray& notes)
{
    struct Damage {
        qsizetype offset;
        unsigned char mask;
        const char *message;
    };
    // Wire offsets belong to these independently encoded package fixtures.
    // These two malformed encodings are checksum-free: entropy validation,
    // rather than a checksum or unrelated tar validation, must reject them.
    for (const auto damage : {
             Damage { 15, 0x80, "invalid Huffman weights reject inside a real compressed package" },
             Damage { 16, 0x08, "invalid FSE accuracy rejects inside compressed Huffman weights" } }) {
        auto corrupt = plain;
        corrupt[damage.offset] = char(static_cast<unsigned char>(corrupt.at(damage.offset)) ^ damage.mask);
        rejectAndRecover(corrupt, damage.message, plain, notes);
    }

    // Header, content size, frame length and valid tar plaintext are unchanged
    // controls. Payload bit flips must never silently publish altered members,
    // including when an altered entropy stream remains otherwise decodable.
    for (const auto damage : {
             Damage { 15, 0x80, "checksummed package rejects altered Huffman weight encoding" },
             Damage { 16, 0x08, "checksummed package rejects altered FSE weight distribution" },
             Damage { 60, 0x01, "checksummed package rejects altered Huffman literal bitstream" },
             Damage { 517, 0x01, "checksummed package rejects altered FSE sequence bitstream" },
             Damage { 601, 0x01, "checksummed package rejects a missing first-block FSE terminal marker" },
             Damage { 633, 0x02, "checksummed package rejects a missing final-block FSE terminal marker" } }) {
        auto corrupt = checked;
        corrupt[damage.offset] = char(static_cast<unsigned char>(corrupt.at(damage.offset)) ^ damage.mask);
        rejectAndRecover(corrupt, damage.message, checked, notes);
    }
    // Only the encoder-produced checksum bytes change: all members and their
    // tar headers remain valid, so rejection cannot be attributed to tar rules.
    for (qsizetype byte = checked.size() - 4; byte < checked.size(); ++byte) {
        auto corrupt = checked;
        corrupt[byte] = char(static_cast<unsigned char>(corrupt.at(byte)) ^ 1);
        rejectAndRecover(corrupt, "a mismatched content checksum rejects an otherwise valid package", checked, notes);
    }
}

void frameAndExpansionBounds(const QByteArray& valid, const QByteArray& notes)
{
    struct Damage { qsizetype offset; unsigned char mask; };
    for (const auto damage : { Damage { 0, 1 }, Damage { 4, 8 }, Damage { 9, 2 }, Damage { 602, 2 } }) {
        auto corrupt = valid;
        corrupt[damage.offset] = char(static_cast<unsigned char>(corrupt.at(damage.offset)) ^ damage.mask);
        rejectAndRecover(corrupt, "corrupt frame and block structure never delivers a package", valid, notes);
    }
    rejectAndRecover(valid + valid, "one package cannot contain concatenated zstd frames", valid, notes);
    rejectAndRecover(valid + QByteArrayLiteral("trailing data"),
        "a compressed package cannot ignore trailing bytes", valid, notes);
    rejectAndRecover(archiveBytes(kOversized),
        "an independently encoded package exceeding the expanded ceiling is refused", valid, notes);
    // The CLI's --no-content-size encoding has byte-identical compressed
    // blocks: omit the four-byte size after its window descriptor. Sharing
    // those precomputed blocks avoids duplicating a 4 KiB binary fixture.
    auto oversizedUnknown = archiveBytes(kOversized);
    oversizedUnknown[4] = char(0);
    oversizedUnknown.remove(6, 4);
    rejectAndRecover(oversizedUnknown,
        "unknown-size compressed expansion exceeding the consumer ceiling is refused", valid, notes);

    // The accepted frame uses a four-byte little-endian content-size field.
    // Altering only that declaration must not allow an under-sized destination,
    // accept a mismatched actual expansion, or bypass the package size ceiling.
    for (const uint32_t declared : { uint32_t(0), uint32_t(1), uint32_t(296959), uint32_t(296961),
             uint32_t(34 * 1024 * 1024), UINT32_MAX }) {
        auto corrupt = valid;
        for (int byte = 0; byte < 4; ++byte)
            corrupt[5 + byte] = char((declared >> (8 * byte)) & 0xff);
        rejectAndRecover(corrupt, "untrusted declared output sizes cannot deliver an oversized or partial package",
            valid, notes);
    }
}

